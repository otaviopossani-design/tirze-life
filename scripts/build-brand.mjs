import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const tokens=JSON.parse(fs.readFileSync(path.join(root,'design/brand-tokens.json'),'utf8'));
const vars=Object.entries(tokens.colors).map(([k,v])=>'--brand-'+k.replace(/[A-Z]/g,c=>'-'+c.toLowerCase())+':'+v).join(';');
const header='/* Generated by scripts/build-brand.mjs from design/brand-tokens.json. */\n';
const font=url=>'@font-face{font-family:Inter;src:url("'+url+'") format("woff2");font-style:normal;font-weight:100 900;font-display:swap}\n';
const body=':root{'+vars+';--brand-font:Inter,ui-sans-serif,-apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif}\n';
const dir=path.join(root,'apps/landing/src/assets');
fs.mkdirSync(dir,{recursive:true});
fs.writeFileSync(path.join(dir,'brand.css'),header+font('./InterVariable.woff2')+body);
let app=header+font('/fonts/InterVariable.woff2')+body;
for(const [name,theme] of Object.entries(tokens.themes)){
 app+='.tl-app[data-theme='+name+']{'+Object.entries(theme).map(([k,v])=>'--'+k+':'+v).join(';')+'}\n';
}
app+='.tl-app{font-family:var(--brand-font);font-optical-sizing:auto}';
fs.writeFileSync(path.join(root,'apps/mobile/src/components/brand.css'),app);
const svg='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect x="2" y="2" width="60" height="60" rx="18" fill="'+tokens.colors.primary+'"/><path d="M13 32h10l6-16 8 32 5-16h9" stroke="#fff" stroke-width="3" fill="none" stroke-linecap="round" stroke-linejoin="round"/></svg>';
fs.writeFileSync(path.join(dir,'brand.svg'),svg);
for(const target of ['apps/mobile/public/fonts','docs/brand/assets']){
 const dest=path.join(root,target);fs.mkdirSync(dest,{recursive:true});
 for(const file of ['InterVariable.woff2','Inter-LICENSE.txt'])if(fs.existsSync(path.join(root,'design',file)))fs.copyFileSync(path.join(root,'design',file),path.join(dest,file));
}
for(const file of ['InterVariable.woff2','Inter-LICENSE.txt'])if(fs.existsSync(path.join(root,'design',file)))fs.copyFileSync(path.join(root,'design',file),path.join(dir,file));
fs.copyFileSync(path.join(dir,'brand.svg'),path.join(root,'docs/brand/assets/brand.svg'));
console.log('Brand assets generated for landing, patient, clinic and guide.');
