const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto('http://localhost:8081/registros', { waitUntil: 'domcontentloaded' });
    await page.getByText('API conectada', { exact: true }).waitFor();
    await page.getByLabel('Como prefere ser chamado(a)?', { exact: true }).fill('Pessoa teste');
    await page.getByRole('checkbox', { name: 'Esta dosagem foi prescrita pelo meu médico.' }).click();
    await page.getByRole('button', { name: 'Salvar meu perfil', exact: true }).click();
    await page.getByText('Perfil salvo. Vamos no seu ritmo.', { exact: true }).waitFor();
    await page.getByRole('button', { name: '+ Registrar aplicação', exact: true }).click();
    await page.getByLabel('Data e hora ISO com fuso', { exact: true }).fill(new Date(Date.now() - 48 * 3600000).toISOString());
    await page.getByRole('checkbox', { name: 'Esta aplicação corresponde à prescrição médica.' }).click();
    await page.getByRole('checkbox', { name: /Confirmei a orientação abdominal/ }).click();
    await page.getByRole('button', { name: 'Salvar aplicação', exact: true }).click();
    await page.getByText('Janela de pico estimada', { exact: true }).waitFor();
    await page.getByRole('button', { name: '+ 250 ml de água', exact: true }).click();
    await page.getByRole('button', { name: '+ 24 g de proteína', exact: true }).click();
    await page.getByRole('button', { name: '+ Registrar meu momento', exact: true }).click();
    for (let index = 0; index < 3; index++) await page.getByRole('button', { name: 'Aumentar quantidade' }).click();
    const responsePromise = page.waitForResponse(response => response.url().endsWith('/v1/real-life/evaluate'));
    await page.getByRole('button', { name: 'Registrar meu momento', exact: true }).click();
    const response = await responsePromise;
    assert.equal(response.status(), 200);
    const body = await response.json();
    assert.equal(body.waterAdjustmentMl, 1000);
    assert.equal(body.dynamicWaterGoalMl, 3800);
    assert.equal(body.phase, 'PEAK_ACTION');
    await page.getByRole('button', { name: 'Concluir', exact: true }).click();
    await page.getByText(/A vida acontece/).waitFor({ state: 'hidden' });
    await page.getByText('Referência do dia: 3.800 ml', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(process.cwd(), 'preview-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: 'Remover evento', exact: true }).click();
    await page.getByText('Referência do dia: 2.800 ml', { exact: true }).waitFor();
    await page.getByLabel('Azia (1 a 5)', { exact: true }).fill('3');
    await page.getByRole('button', { name: 'Registrar como me sinto', exact: true }).click();
    await page.getByRole('button', { name: '+ Registrar meu momento', exact: true }).click();
    await page.getByRole('button', { name: 'Bebida com gás', exact: true }).click();
    const gasPromise = page.waitForResponse(response => response.url().endsWith('/v1/real-life/evaluate'));
    await page.getByRole('button', { name: 'Registrar meu momento', exact: true }).click();
    const gas = await (await gasPromise).json();
    assert.equal(gas.waterAdjustmentMl, 0);
    assert.equal(gas.digestiveWarning, true);
    await page.getByRole('button', { name: 'Concluir', exact: true }).click();
    await page.getByText(/A vida acontece/).waitFor({ state: 'hidden' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(process.cwd(), 'preview-mobile.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    assert.deepEqual(errors, []);
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.getByText('Comece pelo seu perfil', { exact: true }).waitFor();
    console.log('PASS: perfil, prescrição, aplicação, pico, água, proteína, cerveja, API, remoção, sintomas, gás, viewport mobile e sessão volátil.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
