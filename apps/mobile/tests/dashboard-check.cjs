const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 try {
 await page.goto('http://localhost:8081',{waitUntil:'networkidle',timeout:120000});
 await page.getByRole('heading',{name:'Olá, Marina'}).waitFor();
 await page.getByRole('button',{name:'Escuro',exact:true}).click();
 assert.equal(await page.locator('.tl-app').evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(11, 18, 32)');
 assert.ok(await page.locator('.tl-app').evaluate(e=>e.getBoundingClientRect().bottom>=document.querySelector('.tl-footer').getBoundingClientRect().bottom));
 await page.screenshot({path:path.join(process.cwd(),'preview-dashboard-dark.png'),fullPage:true,animations:"disabled"});
 await page.getByRole('button',{name:'250 ml de água',exact:true}).click();
 await page.getByText('1,75',{exact:false}).first().waitFor();
 await page.getByRole('button',{name:'Concluir Almoço',exact:true}).click();
 await page.getByRole('button',{name:'Desmarcar Almoço',exact:true}).waitFor();
 assert.ok((await page.locator('.protein .tl-ring strong').innerText()).includes('1'));
 await page.getByRole('button',{name:'Desmarcar Almoço',exact:true}).click();
 assert.ok((await page.locator('.protein .tl-ring strong').innerText()).includes('0'));
 await page.getByRole('button',{name:'Enjoo / pouca fome',exact:true}).click();
 await page.getByText('Frango desfiado com purê de batata e cenoura',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Claro'}).click();
 assert.equal(await page.locator('.tl-app').getAttribute('data-theme'),'clean');
 await page.screenshot({path:path.join(process.cwd(),'preview-dashboard-clean.png'),fullPage:true,animations:"disabled"});
 await page.getByRole('button',{name:'Suave'}).click();
 await page.screenshot({path:path.join(process.cwd(),'preview-dashboard-warm.png'),fullPage:true,animations:"disabled"});
 await page.getByRole('button',{name:'Registrar meu momento',exact:true}).click();
 await page.getByLabel('Tipo de momento').selectOption('Uma comemoração');
 await page.getByRole('button',{name:'Guardar meu momento',exact:true}).click();
 await page.getByRole('button',{name:'Escrever no diário',exact:true}).click();
 await page.getByLabel('Meu relato',{exact:true}).fill('Hoje me senti bem.');
 await page.getByRole('button',{name:'Salvar meu relato',exact:true}).click();
 await page.getByText('Hoje me senti bem.',{exact:true}).waitFor();
 await page.getByText('Uma comemoração · Respeitei minha saciedade.',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Registrar aplicação',exact:true}).click();
 await page.getByLabel('Local do registro').selectOption('Abdômen superior direito');
 await page.getByRole('button',{name:'Salvar registro de exemplo',exact:true}).click();
 await page.getByRole('button',{name:'Meu tratamento',exact:true}).click();
 await page.getByText('Abdômen superior direito',{exact:true}).first().waitFor();
 await page.getByRole('button',{name:'Minha evolução',exact:true}).click();
 await page.getByRole('heading',{name:'Sua evolução é feita de muitos cuidados.'}).waitFor();
 await page.getByRole('button',{name:'Visão geral',exact:true}).click();
 await page.getByRole('button',{name:'Escuro'}).click();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(process.cwd(),'preview-dashboard-mobile.png'),fullPage:true,animations:"disabled"});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.getByRole('navigation',{name:'Navegação móvel'}).getByRole('button',{name:'Plano alimentar'}).click();
 await page.getByRole('heading',{name:'Jantar',exact:true}).waitFor();
 await page.setViewportSize({width:320,height:740});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.getByRole('navigation',{name:'Navegação móvel'}).getByRole('button',{name:'Visão geral'}).click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.locator('.tl-app').getAttribute('data-theme'),'dark');
 assert.ok((await page.locator('.protein .tl-ring strong').innerText()).includes('0'));
 assert.deepEqual(errors,[]);
 console.log('PASS: 3 temas, água, refeições reversíveis, orientação para enjoo, diário, momentos, aplicação, evolução, navegação móvel, 320/390px, plano e registros locais persistentes e ausência de erros JS.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
