const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const origin=process.env.TIRZELIFE_TEST_ORIGIN||'http://localhost:8081';
const output=process.env.TIRZELIFE_PREVIEW_DIR||path.resolve(__dirname,'../../../.local/previews');
const recordKey='tirzelife-coordination-demo-v1:TL-001';
const button=(scope,name)=>scope.getByRole('button',{name,exact:true});
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1050},timezoneId:'America/Sao_Paulo',reducedMotion:'reduce'});
 context.setDefaultTimeout(18000);
 const patient=await context.newPage(),clinic=await context.newPage(),errors=[];
 for(const p of [patient,clinic])p.on('pageerror',e=>errors.push(e.message));
 const nav=page=>page.getByRole('navigation',{name:page===patient?'Navegação principal':'Navegação da clínica',exact:true});
 const read=()=>patient.evaluate(k=>JSON.parse(localStorage.getItem(k)),recordKey);
 const waitEntry=category=>patient.waitForFunction(({key,category})=>JSON.parse(localStorage.getItem(key)||'null')?.journal.some(j=>j.category===category),{key:recordKey,category});
 const note='Relato rápido QA: organizei meu almoço no plantão e quero guardar este contexto.';
 const activityNote='Movimento QA: caminhada confortável registrada na minha rotina.';
 try{
  await fs.mkdir(output,{recursive:true});
  await patient.goto(origin+'/?view=home',{waitUntil:'networkidle'});
  await clinic.goto(origin+'/clinica?view=patients',{waitUntil:'networkidle'});
  await button(patient,'250 ml de água').click();
  await patient.waitForFunction(key=>JSON.parse(localStorage.getItem(key)||'null')?.journal.some(j=>j.amountMl===250),recordKey);
  await patient.locator('.tl-moods button').nth(2).click();
  await waitEntry('checkin');
  await patient.reload({waitUntil:'networkidle'});
  assert.equal(await patient.locator('.tl-moods button').nth(2).getAttribute('aria-pressed'),'true');
  assert.match(await patient.locator('.tl-metric-card').first().innerText(),/1,75/);
  await button(patient.locator('.tl-page-heading'),'Registrar aplicação').click();
  const dialog=patient.locator('dialog[open]');
  await dialog.getByLabel('Medicamento informado',{exact:true}).fill('Tirzepatida');
  await dialog.getByLabel('Dose informada (opcional)',{exact:true}).fill('5 mg');
  await dialog.getByLabel(/^Local do registro/).selectOption('Coxa direita');
  await button(dialog,'Salvar registro de exemplo').click();
  await waitEntry('medication');
  await button(nav(patient),'Meu diário').click();
  await patient.getByLabel('Meu relato',{exact:true}).fill(note);
  await button(patient,'Salvar meu relato').click();
  await patient.locator('.tl-entry').filter({hasText:note}).waitFor();
  await button(nav(patient),'Plano alimentar').click();
  const meal=patient.locator('.nt-meal').first();
  const food=await meal.locator('.nt-food').innerText();
  await meal.getByRole('button',{name:/Concluir /}).click();
  await button(nav(patient),'Movimento').click();
  await button(patient,'Registrar caminhada').click();
  await patient.getByLabel('Minutos realizados',{exact:true}).fill('12');
  await patient.getByLabel('Observações da atividade',{exact:true}).fill(activityNote);
  await button(patient,'Salvar atividade').click();
  await patient.getByRole('status').filter({hasText:'Atividade registrada'}).waitFor();
  await patient.reload({waitUntil:'networkidle'});
  await patient.getByText(activityNote,{exact:true}).waitFor();
  const record=await read();
  assert.ok(record.journal.some(j=>j.originalText===note));
  assert.ok(record.journal.some(j=>j.category==='medication'&&j.doseText==='5 mg'));
  const row=clinic.locator('tbody tr').filter({hasText:'Marina Oliveira'});
  await row.getByText('88%',{exact:true}).waitFor();
  await row.getByText('25%',{exact:true}).waitFor();
  await button(clinic,'Abrir ficha de Marina Oliveira').click();
  const detail=clinic.locator('dialog[open]');
  await detail.locator('.cl-detail-block').filter({hasText:note}).waitFor();
  assert.match(await detail.locator('.cl-detail-metrics').innerText(),/1\/7/);
  await clinic.getByRole('tab',{name:'Diário',exact:true}).click();
  const timeline=clinic.getByTestId('coordination-root').locator('.co-timeline');
  await timeline.getByText(note,{exact:true}).waitFor();
  await timeline.getByText(activityNote,{exact:false}).waitFor();
  await timeline.getByText(food,{exact:false}).waitFor();
  await timeline.getByText('Coxa direita',{exact:false}).waitFor();
  await timeline.getByText('250 ml de água informados.',{exact:false}).waitFor();
  await timeline.getByText('Bem',{exact:true}).waitFor();
  await clinic.screenshot({path:path.join(output,'quick-journal-clinic-desktop.png')});
  const downloadPromise=clinic.waitForEvent('download');
  await button(clinic.getByTestId('coordination-root'),'Exportar JSON').click();
  const download=await downloadPromise;
  const downloaded=path.join(output,'quick-journal-export.json');
  await download.saveAs(downloaded);
  const exported=JSON.parse(await fs.readFile(downloaded,'utf8'));
  assert.equal(exported.patientId,'TL-001');
  assert.ok(exported.events.some(e=>e.originalText===note));
  await button(nav(patient),'Plano combinado').click();
  const panel=patient.getByTestId('coordination-root');
  await button(panel.getByRole('navigation',{name:'Áreas do acompanhamento',exact:true}),'Histórico').click();
  await panel.locator('.co-timeline').getByText(note,{exact:true}).waitFor();
  await patient.screenshot({path:path.join(output,'quick-journal-patient-desktop.png')});
  const widths=[];
  for(const width of [390,320]){
   await patient.setViewportSize({width,height:900});
   await patient.goto(origin+'/?view=care',{waitUntil:'networkidle'});
   await button(patient.getByTestId('coordination-root').getByRole('navigation',{name:'Áreas do acompanhamento'}),'Histórico').click();
   const dim=await patient.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth,nav:document.querySelector('.tl-mobile-nav').clientWidth,navScroll:document.querySelector('.tl-mobile-nav').scrollWidth,buttons:[...document.querySelectorAll('.tl-mobile-nav button')].map(b=>b.getBoundingClientRect().width)}));
   assert.ok(dim.document<=width+1,JSON.stringify(dim));
   assert.equal(dim.buttons.length,8);assert.ok(dim.buttons.every(w=>w>=56));
   widths.push({mode:'patient',width,...dim});
   await patient.screenshot({path:path.join(output,'quick-journal-patient-'+width+'.png')});
   await clinic.setViewportSize({width,height:900});
   const clinical=await clinic.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth,dialog:document.querySelector('dialog[open]').clientWidth,dialogScroll:document.querySelector('dialog[open]').scrollWidth,nav:document.querySelector('.tl-mobile-nav').clientWidth,navScroll:document.querySelector('.tl-mobile-nav').scrollWidth,buttons:[...document.querySelectorAll('.tl-mobile-nav button')].map(b=>b.getBoundingClientRect().width)}));
   assert.ok(clinical.document<=width+1,JSON.stringify(clinical));
   assert.ok(clinical.dialogScroll<=clinical.dialog+1,JSON.stringify(clinical));
   assert.equal(clinical.buttons.length,7);assert.ok(clinical.buttons.every(w=>w>=48));
   widths.push({mode:'clinic',width,...clinical});
   await clinic.screenshot({path:path.join(output,'quick-journal-clinic-'+width+'.png')});
  }
  await clinic.reload({waitUntil:'networkidle'});
  await button(clinic,'Abrir ficha de Marina Oliveira').click();
  await clinic.locator('.cl-detail-block').filter({hasText:note}).waitFor();
  assert.equal(errors.length,0,errors.join('\n'));
  const result={passed:true,checkedAt:new Date().toISOString(),checks:['quick-water','checkin','medication','diary','meal','activity','cross-tab-clinic-metrics','shared-timeline','reload-persistence','local-json-export','mobile320-390','no-browser-errors'],widths};
  await fs.writeFile(path.join(output,'quick-journal-validation.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));
 }catch(error){
  await patient.screenshot({path:path.join(output,'quick-journal-failure-patient.png')}).catch(()=>{});
  await clinic.screenshot({path:path.join(output,'quick-journal-failure-clinic.png')}).catch(()=>{});
  console.error(error);process.exitCode=1;
 }finally{await browser.close();}
})();
